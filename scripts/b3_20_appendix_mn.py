P('口令是带教老师在教学中使用的简短指令，用于引导学员完成功法动作。好的口令应该准确、简洁、节奏感强、易于理解和记忆。口令设计需要遵循以下规范。第一，准确性规范。口令必须准确描述动作的方向、路线和节奏。例如"上举"要说明是双手交叉上举还是单手上举，"左推"要说明是左手向左推还是右手向左推。模糊的口令会让学员产生困惑。第二，简洁性规范。口令要简短精炼，每个口令不超过六个字。太长的口令会占用练习时间，影响练习的流畅性。例如"双手交叉上举翻掌托天"可以简化为"交叉——上举——托天"。第三，节奏性规范。口令的节奏要与动作的节奏相匹配。八段锦的口令一般采用四拍或六拍节奏，太极拳的口令一般采用八拍节奏。口令的间隔时间要均匀，不能忽快忽慢。第四，引导性规范。口令不仅要描述动作，还要引导学员的注意力和意念。例如"托天——拉伸——感受脊柱拉长"中，前两个词是动作指令，第三个词是意念引导。这种"动作+意念"的口令模式可以帮助学员更好地体会功法的内涵。')

