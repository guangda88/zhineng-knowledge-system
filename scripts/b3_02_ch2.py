P('站姿呼吸练习是最常用的呼吸训练方式，适合在晨练、课间、工间等场合进行。站姿呼吸的基本要领是：两脚平行开立，与肩同宽，膝盖微屈，重心平稳；头正项竖，下颌微收，百会上领；含胸拔背，沉肩坠肘，松腰敛臀；双手自然下垂或抱于腹前。站姿呼吸的优点是气血运行畅通，身体稳定，便于集中注意力。初学者每次练习五至十分钟，逐渐延长到二十至三十分钟。站姿呼吸训练时要注意保持身体放松，不要僵硬用力，呼吸要自然流畅，不要刻意控制。如果出现腿酸、腰累等不适，可以适当活动一下再继续。')
