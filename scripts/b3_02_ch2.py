P('卧姿呼吸练习主要在睡前或体弱者练习时使用。卧姿呼吸分为仰卧式和侧卧式两种。仰卧式是平躺在床上或垫子上，两脚自然分开，双手放在身体两侧，掌心向上。侧卧式是侧卧在床上或垫子上，双腿微屈，一手放在枕头旁，一手放在大腿上。卧姿呼吸的优点是身体完全放松，不受重力影响，特别适合老年人、体弱者和卧床患者。练习时要注意枕头高度适中，不要太高或太低；被子不要太重，以免影响呼吸；全身肌肉要放松，特别是面部和肩部肌肉。卧姿呼吸每次练习十至十五分钟，是改善睡眠的有效方法。')

