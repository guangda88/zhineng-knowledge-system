H('2.2 吐纳、闭气、调息规范', 3)
P('吐纳是气功呼吸训练的基本功法，"吐"为呼气，"纳"为吸气。吐纳训练强调呼吸的节奏和深度，要求呼吸做到深、长、细、匀、柔。深是指呼吸要深达丹田，不要浅尝辄止。长是指每次呼吸的时间要足够长，不要急促短浅。细是指呼吸的气流要细微如丝，不要粗重有力。匀是指呼吸的节奏要均匀稳定，不要忽快忽慢。柔是指呼吸要柔和自然，不要用力控制。吐纳训练可以分为坐式吐纳、站式吐纳和卧式吐纳三种，初学者建议从坐式吐纳开始练习。')
P('闭气是呼吸训练中的一种特殊方法，是在吸气或呼气之后暂时屏住呼吸。闭气分为吸后闭气和呼后闭气两种。吸后闭气是指在吸气之后屏住呼吸，保持一段时间再呼气。呼后闭气是指在呼气之后屏住呼吸，保持一段时间再吸气。闭气的时间不宜过长，一般初学者以三至五秒为宜，随着练习深入可以逐渐延长。闭气训练可以提高肺活量，增强呼吸控制能力，调节自主神经系统。但闭气训练有一定的风险，心脏病、高血压患者不宜练习，头晕、心慌时应立即停止。')
P('调息是指通过调整呼吸的频率、深度、节奏和方式来调节身心状态。调息是气功训练中贯穿始终的基本功，不同的功法和练习阶段需要不同的调息方法。调息的一般原则是先调形、后调息、再调心，即先调整好身体姿势，然后调整呼吸，最后调整意念。调息的步骤包括：第一步，自然呼吸，放松身心；第二步，过渡到腹式呼吸，加深呼吸；第三步，配合动作和意念，形成完整的练功状态。调息训练需要长期练习才能掌握，带教老师要耐心指导，不要急于求成。')

