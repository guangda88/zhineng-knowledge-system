P('八段锦教学中，学员常见的错误动作需要带教老师及时发现并纠正。第一式"两手托天理三焦"的常见错误是耸肩和挺胸。耸肩会导致颈部肌肉紧张，影响气血运行。纠正方法是提醒学员沉肩坠肘，想象肩上放着重物。挺胸会导致胸椎僵硬，影响呼吸顺畅。纠正方法是提醒学员含胸拔背，胸部微含，背部自然伸展。第二式"左右开弓似射雕"的常见错误是手臂不直和马步不稳。手臂不直会导致动作不到位，影响功效。纠正方法是提醒学员充分伸展手臂，手指指向前方。马步不稳会影响身体平衡。纠正方法是提醒学员双脚踏实地面，重心下沉。')
P('第三式"调理脾胃须单举"的常见错误是身体歪斜和手臂弯曲。身体歪斜会导致脊柱侧弯，影响气血运行。纠正方法是提醒学员保持身体中正，不要随着手臂的上下而倾斜。手臂弯曲会导致拉伸不充分。纠正方法是提醒学员充分伸展手臂，肘关节不要弯曲。第四式"五劳七伤往后瞧"的常见错误是上身跟着转和转头过猛。上身跟着转会减弱对颈椎的锻炼效果。纠正方法是提醒学员保持肩膀不动，只转头。转头过猛会导致颈部肌肉拉伤。纠正方法是提醒学员转头要缓慢平稳，不要用力过猛。')
