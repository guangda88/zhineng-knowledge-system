H('3.2 混元桩：要领、呼吸、意念', 3)
P('混元桩是在无极桩基础上发展起来的进阶桩法，是站桩功法中最核心、最常用的桩法。"混元"意为混沌未分、浑然一体，代表着宇宙最初的状态。混元桩的训练目的是在无极桩放松入静的基础上，通过特定的手臂姿势和意念活动，培育内气、增强体质、调和身心。混元桩的身形要领与无极桩基本相同，只是在手臂姿势上有所不同。混元桩的手臂姿势是：双手在胸前环抱，如抱一个气球，两手与胸同高，距离胸部约二十至三十厘米，十指分开，掌心向内，手指相对但不要接触。手臂要形成一个大圆，肘部略低于手，腋下要虚空，如夹着一个鸡蛋。')
P('混元桩的呼吸训练是在腹式呼吸的基础上进行的。具体的呼吸方法是：吸气时，想象天地精华之气从全身毛孔吸入，汇聚于丹田，腹部微微隆起；呼气时，想象体内浊气从全身毛孔呼出，腹部微微内收。呼吸要做到深、长、细、匀，不要刻意用力，要顺其自然。随着练习的深入，呼吸会变得越来越细微，甚至感觉不到呼吸的存在，这就是"胎息"的境界。混元桩的呼吸训练要与身形放松相配合，在保持身形中正的前提下进行呼吸，不要因为呼吸而改变身形。')
P('混元桩的意念训练是桩功的核心和灵魂。意念训练的目的是通过特定的思维活动，引导内气的生成和运行。混元桩的意念方法主要有以下几种：第一种是"抱球意念"，想象双手之间抱着一个气球，这个气球有弹性、有温度，手指可以感受到气球的膨胀和收缩。第二种是"丹田意念"，将注意力集中在下丹田（脐下三寸），想象丹田处有一个光球，随着呼吸的进出而明暗变化。第三种是"整体意念"，想象全身被一层温暖的光芒包裹着，从头到脚都充满了能量。意念训练要轻松自然，不要刻意追求感觉，如果杂念出现，轻轻地将注意力拉回来即可。')

