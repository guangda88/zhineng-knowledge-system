        r.font.name='宋体'; r.element.rPr.rFonts.set(qn('w:eastAsia'),'宋体')
        c._tc.get_or_add_tcPr().append(parse_xml(f'<w:shd {nsdecls("w")} w:fill="D9E2F3"/>'))
