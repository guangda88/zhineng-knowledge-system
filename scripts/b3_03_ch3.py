P('无极桩的具体操作步骤如下。第一步，两脚平行开立，与肩同宽或略宽于肩，脚尖朝前，重心落在两脚之间。第二步，膝盖微屈，不要超过脚尖，保持膝盖的弹性。第三步，腰部放松，臀部微收，尾骨下沉，使脊柱保持自然的生理弯曲。第四步，含胸拔背，不要挺胸也不要驼背，背部自然伸展。第五步，沉肩坠肘，肩膀放松下沉，肘部自然弯曲。第六步，头正项竖，下颌微收，百会穴向上领起，如有一根线从头顶向上牵引。第七步，双眼微闭或目视前方，面部表情放松，嘴角微带笑意。第八步，双手自然下垂于身体两侧，掌心向内，十指自然分开。')
P('无极桩的放松训练是站桩的核心内容。放松不是松垮，而是要在保持身形中正的前提下，让全身肌肉达到最大程度的松弛。放松的方法是从上到下依次放松：先放松头部和面部，然后放松颈部和肩膀，接着放松胸部和背部，再放松腰部和臀部，最后放松大腿、小腿和双脚。每放松一个部位，都要体会该部位的感觉，如果发现有紧张的肌肉，要有意识地让它松开。放松训练需要反复练习，一般需要数周甚至数月的时间才能真正体会到全身放松的感觉。入静是无极桩的高层次要求，是指在放松的基础上，让心神安定下来，排除杂念，进入一种平静、宁静的状态。入静的方法是将注意力集中在丹田或呼吸上，感受气息的进出或丹田的温热。')

