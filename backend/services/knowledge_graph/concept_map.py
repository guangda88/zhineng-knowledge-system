def get_related_domains(query: str) -> List[str]:
    """从查询中提取相关领域

    对查询中的每个概念查找关联领域，返回去重后的领域列表。
    """
    domains: Set[str] = set()
    for concept, related in CONCEPT_DOMAIN_MAP.items():
        if concept in query:
            domains.update(related)
    return [d for d in NINE_DOMAINS if d in domains]


def get_concept_info(query: str) -> List[Dict[str, object]]:
    """从查询中提取匹配的概念及其关联领域"""
    matches = []
    for concept, related in CONCEPT_DOMAIN_MAP.items():
        if concept in query:
            matches.append({
                "concept": concept,
                "domains": related,
                "cross_domain": len(related) > 1,
            })
    return matches


def get_cross_domain_concepts(domain: str) -> List[Tuple[str, List[str]]]:
    """获取某领域的所有跨域概念"""
    results = []
    for concept, domains in CONCEPT_DOMAIN_MAP.items():
        if domain in domains and len(domains) > 1:
            results.append((concept, domains))
    return results
